<?php
// Writes data/extra-word-counts.txt: how often each word in data/extra-words.txt appears in
// film subtitles (the full OpenSubtitles list from hermitdave/FrequencyWords, CC BY-SA 4.0).
// The build uses it to order the hand-added words by how common they are, so a fairly common
// word added by hand (thicken) doesn't score as one of the rarest. Rerun after adding words:
//
//   php -d memory_limit=1G scripts/count-extra-words.php
//   php scripts/build-dictionary.php

declare(strict_types=1);

const FULL_FREQ_URL = 'https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/en/en_full.txt';

$dataDir = dirname(__DIR__) . '/data';
$wanted = [];
foreach (file("$dataDir/extra-words.txt", FILE_IGNORE_NEW_LINES) as $line) {
    $word = strtolower(trim(preg_replace('/#.*/', '', $line)));
    if ($word !== '') $wanted[$word] = true;
}

$raw = @file_get_contents(FULL_FREQ_URL);
if ($raw === false) {
    fwrite(STDERR, "Couldn't download " . FULL_FREQ_URL . "\n");
    exit(1);
}
$counts = [];
foreach (explode("\n", $raw) as $line) {
    [$word, $count] = explode(' ', trim($line)) + [null, 0];
    $word = strtolower((string) $word);
    if (isset($wanted[$word]) && !isset($counts[$word])) $counts[$word] = (int) $count;
}
arsort($counts);

$out = "# How often each word in extra-words.txt appears in film subtitles, most first.\n"
    . "# Generated by scripts/count-extra-words.php; the build orders hand-added words by it.\n"
    . "# Words not listed weren't found and count as the rarest.\n";
foreach ($counts as $word => $count) $out .= "$word $count\n";
file_put_contents("$dataDir/extra-word-counts.txt", $out);
echo 'Wrote data/extra-word-counts.txt: ' . count($counts) . ' of ' . count($wanted) . " hand-added words found in the subtitles\n";
