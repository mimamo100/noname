"""Writes data/verb-forms.txt: each -ing and -ed form with the verb it's a form of.

A verb's -ing and -ed forms are one answer with it and are judged as it: "running" scores as
"run", is 3 letters long, and doesn't end in G (except on a meaning prompt whose list names the
word, such as "swimming" for "A sport"). The family rules join forms to roots by their endings
alone, which goes wrong ("browsed" to "brow", "wasted" to "wast"), so the links come from
WordNet's lemmatiser instead, and only where the root is in the dictionary. The file also adds
the forms the dictionary lacks: ENABLE's forms of dictionary verbs ("creasing", "heckled").

Needs NLTK, so it only runs on a development machine; the output is committed:

    pip install nltk
    python -c "import nltk; nltk.download('wordnet')"
    php scripts/build-dictionary.php          (so data/dictionary.php is current)
    python scripts/find-verb-forms.py
    php scripts/build-dictionary.php

A form that should stand on its own (a noun first: "earring") goes in data/family-breaks.txt,
which this file then ignores.
"""
import json
import os
import subprocess
import urllib.request

from nltk.corpus import wordnet as wn

ENABLE_URL = "https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data")


def dictionary_words():
    # The built dictionary (data/dictionary.php), as PHP is the only reader of it.
    code = "$d = require $argv[1]; echo json_encode($d['words']);"
    out = subprocess.run(["php", "-r", code, os.path.join(DATA, "dictionary.php")], capture_output=True, text=True, check=True)
    return set(json.loads(out.stdout))


def read_list(name):
    with open(os.path.join(DATA, name), encoding="utf-8") as f:
        return [line.split("#")[0].strip().lower() for line in f if line.split("#")[0].strip()]


def regular_forms(root):
    """The spellings a regular -ing or -ed form of root could have."""
    forms = {root + "ing", root + "ed"}
    if root.endswith("e"):
        forms |= {root[:-1] + "ing", root + "d"}
    if root.endswith("ie"):
        forms.add(root[:-2] + "ying")
    if root.endswith("y") and len(root) > 1 and root[-2] not in "aeiou":
        forms.add(root[:-1] + "ied")
    if len(root) > 1 and root[-1] not in "aeiouwxy":
        forms |= {root + root[-1] + "ing", root + root[-1] + "ed"}  # stop, stopping; travel, travelling
    if root.endswith("c"):
        forms |= {root + "king", root + "ked"}  # picnic, picnicking
    return forms


def main():
    words = dictionary_words()
    breaks = set(read_list("family-breaks.txt"))
    enable = urllib.request.urlopen(ENABLE_URL).read().decode().split()
    links = {}
    for form in sorted(words | set(enable)):
        if form in breaks or len(form) < 5 or not (form.endswith("ing") or form.endswith("ed")):
            continue
        root = wn.morphy(form, wn.VERB)
        if root and root != form and root in words and form in regular_forms(root):
            links[form] = root
    added = sum(1 for f in links if f not in words)
    with open(os.path.join(DATA, "verb-forms.txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by scripts/find-verb-forms.py: each -ing and -ed form, then its verb.\n")
        f.write("# A form not in the dictionary is added beside its verb. Don't edit by hand: to let a\n")
        f.write("# form stand on its own, add it to family-breaks.txt and run the script again.\n")
        for form, root in sorted(links.items()):
            f.write(f"{form} {root}\n")
    print(f"Wrote data/verb-forms.txt: {len(links)} forms, {added} of them new to the dictionary")


main()
