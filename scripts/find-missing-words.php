<?php
// Lists common words the dictionary misses, for a person to review (see
// docs/dictionary-review/MISSING-WORDS.md). Nothing in the game changes: approved words are
// added to data/extra-words.txt by hand.
//
// data/words.txt only takes words from the top 50,000 of the OpenSubtitles frequency list, so
// ordinary words just below that line are missing (befit, filmy). This script takes the full
// frequency list (about 1.6 million entries) and lists the words that are in ENABLE but not
// in the dictionary, most frequent first.
//
//   php scripts/find-missing-words.php [limit] [output file]
//
// limit: how many new words to list (default 3000). Output: by default
// docs/dictionary-review/missing-words.txt.

declare(strict_types=1);

require __DIR__ . '/../src/WordFamilies.php';

const ENABLE_URL = 'https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt';
const FULL_FREQ_URL = 'https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/en/en_full.txt';
/** Words seen fewer times than this in the subtitles are too rare to be worth reviewing. */
const MIN_COUNT = 20;

$root = dirname(__DIR__);
$limit = (int) ($argv[1] ?? 3000);
$out = $argv[2] ?? "$root/docs/dictionary-review/missing-words.txt";

$dictionary = require "$root/data/dictionary.php";
$known = array_flip($dictionary['words']);
$blocked = array_flip($dictionary['blocked']);
$enable = array_flip(array_map('trim', explode("\n", fetch(ENABLE_URL))));

// Candidates: in ENABLE, not in the dictionary or the blocklist, seen often enough.
$new = [];   // Words of their own.
$forms = []; // Plurals and -ed/-ing forms of words we have: these matter less, as families bring most along.
foreach (explode("\n", fetch(FULL_FREQ_URL)) as $line) {
    [$word, $count] = explode(' ', trim($line)) + [null, 0];
    $word = strtolower((string) $word);
    if ((int) $count < MIN_COUNT) break; // The list is sorted by count.
    if (strlen($word) < 3 || !preg_match('/^[a-z]+$/', $word) || !isset($enable[$word])) continue;
    if (isset($known[$word]) || isset($blocked[$word])) continue;
    $base = null;
    foreach (WordFamilies::rootCandidates($word) as $candidate) {
        if ($candidate !== $word && isset($known[$candidate])) { $base = $candidate; break; }
    }
    if ($base === null) $new[] = [$word, (int) $count];
    else $forms[] = [$word, (int) $count, $base];
}

$lines = [
    '# Common words missing from the dictionary, for review (see MISSING-WORDS.md).',
    '# Generated by scripts/find-missing-words.php on ' . date('j M Y') . '. Each line: word, times seen in film',
    '# subtitles. Copy the ones that should count into data/extra-words.txt.',
    '',
    '## New words, most frequent first (' . min($limit, count($new)) . ' of ' . count($new) . ')',
];
foreach (array_slice($new, 0, $limit) as [$word, $count]) $lines[] = sprintf('%-20s %d', $word, $count);
$lines[] = '';
$lines[] = '## Forms of words we have (plurals, -ed, -ing), most frequent first (' . min($limit, count($forms)) . ' of ' . count($forms) . ')';
$lines[] = '# Only needed where the form is an answer in its own right (a missing plural of a listed bird, say).';
foreach (array_slice($forms, 0, $limit) as [$word, $count, $base]) $lines[] = sprintf('%-20s %-8d (%s)', $word, $count, $base);

if (!is_dir(dirname($out))) mkdir(dirname($out), 0777, true);
file_put_contents($out, implode("\n", $lines) . "\n");
echo 'Wrote ' . min($limit, count($new)) . ' new words and ' . min($limit, count($forms)) . " forms to $out\n";

function fetch(string $url): string
{
    $data = @file_get_contents($url);
    if ($data === false) {
        fwrite(STDERR, "Couldn't download $url\n");
        exit(1);
    }
    return $data;
}
